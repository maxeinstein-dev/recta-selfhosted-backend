/**
 * "The sheet takes over": a monthly-sheet expense row that matches a recurrence of the household (same account,
 * same normalized description) for that month does not become a second charge. It either updates the pending
 * transaction the recurrence generated, or, when the recurrence has not run yet, becomes the month's occurrence and
 * moves the recurrence on. This file finds the matches (preview and confirm use the same rules); the writes are
 * in confirmMaxFinImport.
 */
import { prisma } from '../../shared/db/prisma.js';
import { normalizeDescription } from '../recurring-transactions/detect.js';
import { recurrenceNameKeys } from '../recurring-transactions/recurring-aliases.js';
import { anchorDayOf, dayString } from '../recurring-transactions/recurring-dates.js';
import { FOLLOW_LOOKAHEAD_DAYS, plusDays } from '../recurring-transactions/recurring-follow.js';
import { forecastBatch, isIncomeCategory, referenceMonthOf } from '../recurring-transactions/recurring-forecast.js';
import type { MaxFinInstallment, MaxFinSectionKey } from './parsers/maxfin.types.js';

export type RecurringMatch =
  | {
      kind: 'generated';
      transactionId: string;
      recurringId: string;
      /** YYYY-MM-DD of the generated transaction. */
      day: string;
      amount: number;
      /** The generated transaction is already paid (a card occurrence, or paid by hand). */
      paid: boolean;
    }
  | {
      kind: 'recurrence';
      transactionId: null;
      recurringId: string;
      /** YYYY-MM-DD of the recurrence's nextRunAt (inside the sheet month). */
      day: string;
      followLastAmount: boolean;
      endDate: string | null;
      /** Day of month the recurrence is anchored to (its startDate day). */
      anchorDay: number;
      amount: number;
      /** Months between the occurrence date and the month it refers to (null = same month). */
      competenceOffsetMonths?: number | null;
    };

/** Rows that can be taken over by a recurrence: plain expenses, not installments, not the income block. */
export function eligibleForRecurring(row: {
  type: 'INCOME' | 'EXPENSE';
  section: MaxFinSectionKey;
  installment: MaxFinInstallment | null;
}): boolean {
  return row.type === 'EXPENSE' && row.section !== 'income' && row.installment === null;
}

export function recurringMatchDetail(match: RecurringMatch): string {
  if (match.kind === 'generated') {
    return `atualiza a transação gerada de ${match.day.slice(8, 10)}/${match.day.slice(5, 7)}`;
  }
  return 'assume a recorrência e adianta a próxima execução';
}

export interface RecurringMatcher {
  /** Next unused match for the account and description (a match serves one row), or undefined. */
  take(accountId: string, description: string): RecurringMatch | undefined;
}

const NO_MATCHER: RecurringMatcher = { take: () => undefined };

/** 'YYYY-MM' prefix test on a stored day. */
function inMonth(day: string, monthKey: string): boolean {
  return day.startsWith(`${monthKey}-`);
}

/**
 * Candidates of a sheet month: (a) transactions generated by a recurrence in that month (pending, or already paid
 * by hand or because it is a card) and not taken yet (no sourceRef), then (b) active monthly recurrences whose next run falls in the month and that have no
 * transaction in it. Each is keyed by account + normalized description and handed out once, oldest first.
 */
export async function loadRecurringMatcher(
  householdId: string,
  accountIds: string[],
  monthKey: string,
  now: Date = new Date(),
): Promise<RecurringMatcher> {
  if (accountIds.length === 0) return NO_MATCHER;
  const start = new Date(Date.UTC(Number(monthKey.slice(0, 4)), Number(monthKey.slice(5, 7)) - 1, 1));
  const end = new Date(Date.UTC(Number(monthKey.slice(0, 4)), Number(monthKey.slice(5, 7)), 1));

  const generatedWhere = { householdId, type: 'EXPENSE' as const, sourceRef: null, recurringTransactionId: { not: null }, accountId: { in: accountIds } };
  const generatedSelect = { id: true, accountId: true, description: true, date: true, amount: true, paid: true, recurringTransactionId: true, competenceMonth: true } as const;
  let generated = await prisma.transaction.findMany({ where: { ...generatedWhere, date: { gte: start, lt: end } }, select: generatedSelect });
  // Occurrences paid ahead: dated in another month but referring to this one (competence month)
  const ahead = await prisma.transaction.findMany({ where: { ...generatedWhere, competenceMonth: monthKey }, select: generatedSelect });

  const recurrences = await prisma.recurringTransaction.findMany({
    where: { householdId, isActive: true, frequency: 'MONTHLY', accountId: { in: accountIds } },
    select: { id: true, accountId: true, description: true, aliases: true, nextRunAt: true, startDate: true, endDate: true, followLastAmount: true, amount: true, competenceOffsetMonths: true,
      householdId: true, categoryName: true, forecastStrategy: true, forecastWindow: true, dailyRate: true, safetyBusinessDays: true, nonWorkingDays: true, optionalHolidays: true },
  });
  // A recurrence whose next run is farther than today + 31 days is not this month's charge yet (same limit as
  // followLastAmountInTx): a sheet of a far future month must not consume it.
  const limit = plusDays(now, FOLLOW_LOOKAHEAD_DAYS);
  const inWindow = recurrences.filter((r) => inMonth(dayString(r.nextRunAt), monthKey) && dayString(r.nextRunAt) <= limit);
  // Only expense rows are matched (eligibleForRecurring), so an INCOME recurrence is never a candidate: a salary or
  // allowance and an expense paid from the same account can share a description, and the expense must not consume the
  // income's occurrence. A recurrence carries no type of its own: its category decides, as when it runs.
  const income = await Promise.all(inWindow.map((r) => isIncomeCategory(prisma, householdId, r.categoryName)));
  const due = inWindow.filter((_, i) => !income[i]);
  // The amount a recurrence is EXPECTED to carry for the month the occurrence counts for (its strategy decides), not the stored one
  const expected = await forecastBatch(prisma, due);
  const occupied = new Set<string>();
  if (due.length > 0) {
    const present = await prisma.transaction.findMany({
      where: { householdId, recurringTransactionId: { in: due.map((r) => r.id) }, date: { gte: start, lt: end } },
      select: { recurringTransactionId: true },
    });
    for (const t of present) if (t.recurringTransactionId) occupied.add(t.recurringTransactionId);
  }

  // A match is keyed by every name its recurrence answers to (description and aliases) but serves one row only.
  type Slot = { match: RecurringMatch; taken: boolean };
  const pools = new Map<string, Slot[]>();
  const push = (accountId: string, names: Set<string>, match: RecurringMatch) => {
    const slot: Slot = { match, taken: false };
    for (const key of names) {
      const id = `${accountId}|${key}`;
      const list = pools.get(id) ?? [];
      list.push(slot);
      pools.set(id, list);
    }
  };
  // Aliases of the recurrences that generated the month's transactions (they may not be in the `due` window)
  const aliasesOf = new Map<string, string[]>(recurrences.map((r) => [r.id, r.aliases ?? []]));
  const offsetOf = new Map<string, number | null>(recurrences.map((r) => [r.id, r.competenceOffsetMonths ?? null]));
  const missing = [...new Set([...generated, ...ahead].map((t) => t.recurringTransactionId).filter((id): id is string => !!id && !aliasesOf.has(id)))];
  if (missing.length > 0) {
    const extra = await prisma.recurringTransaction.findMany({ where: { householdId, id: { in: missing } }, select: { id: true, aliases: true, competenceOffsetMonths: true } });
    for (const r of extra) {
      aliasesOf.set(r.id, r.aliases ?? []);
      offsetOf.set(r.id, r.competenceOffsetMonths ?? null);
    }
  }
  // A recurrence WITHOUT an offset only has a competence month on an occurrence paid ahead: that one belongs to the month it
  // refers to, not to the month of its date (so the month it is dated in does not see the same bill twice, and the month it
  // refers to finds it). A recurrence with an offset always has one, so it keeps matching by date.
  const noOffset = (t: { recurringTransactionId: string | null }): boolean => t.recurringTransactionId !== null && offsetOf.get(t.recurringTransactionId) === null;
  generated = [
    ...generated.filter((t) => !(t.competenceMonth && t.competenceMonth !== monthKey && noOffset(t))),
    ...ahead.filter((t) => !inMonth(dayString(t.date), monthKey) && noOffset(t)),
  ];

  [...generated]
    .sort((a, b) => dayString(a.date).localeCompare(dayString(b.date)) || a.id.localeCompare(b.id))
    .forEach((t) => {
      if (!t.accountId || !t.recurringTransactionId) return;
      push(t.accountId, recurrenceNameKeys(t.description, aliasesOf.get(t.recurringTransactionId)), {
        kind: 'generated',
        transactionId: t.id,
        recurringId: t.recurringTransactionId,
        day: dayString(t.date),
        amount: t.amount.toNumber(),
        paid: t.paid,
      });
    });
  const generatedRecurrences = new Set(generated.map((t) => t.recurringTransactionId));
  [...due]
    .sort((a, b) => dayString(a.nextRunAt).localeCompare(dayString(b.nextRunAt)) || a.id.localeCompare(b.id))
    .forEach((r) => {
      if (occupied.has(r.id) || generatedRecurrences.has(r.id)) return;
      const nextRun = dayString(r.nextRunAt);
      const endDate = r.endDate ? dayString(r.endDate) : null;
      if (endDate && endDate < nextRun) return;
      push(r.accountId, recurrenceNameKeys(r.description, r.aliases), {
        kind: 'recurrence',
        transactionId: null,
        recurringId: r.id,
        day: nextRun,
        // Only the LAST strategy takes over the sheet's value
        followLastAmount: r.followLastAmount && (r.forecastStrategy ?? 'LAST') === 'LAST',
        endDate,
        anchorDay: anchorDayOf(r.startDate),
        amount: expected.expected(r, referenceMonthOf(r.nextRunAt, r.competenceOffsetMonths)).amount,
        competenceOffsetMonths: r.competenceOffsetMonths ?? null,
      });
    });

  if (pools.size === 0) return NO_MATCHER;
  return {
    take(accountId, description) {
      const list = pools.get(`${accountId}|${normalizeDescription(description)}`);
      const slot = list?.find((s) => !s.taken);
      if (!slot) return undefined;
      slot.taken = true;
      // Generated transactions were pushed first, so they win over recurrences that have not run.
      return slot.match;
    },
  };
}
