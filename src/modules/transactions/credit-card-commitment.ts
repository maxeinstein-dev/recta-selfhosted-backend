/** What one invoice is expected to cost, and how it compares with the income expected for its month. */
export interface CommitmentMonth {
  /** Invoice month, 'YYYY-MM' (the month it is due in). */
  month: string;
  closingDate: string;
  dueDate: string | null;
  state: InvoiceState;
  /** Already on the invoice: postedInstallments + postedRecurrences + postedPurchases (net of refunds). */
  posted: number;
  /** Part of `posted` that comes from installments (rows with installmentId). */
  postedInstallments: number;
  /** Part of `posted` generated by recurrences (rows with recurringTransactionId and no installment). */
  postedRecurrences: number;
  /** Part of `posted` that is neither: plain purchases, the rest of the statement. */
  postedPurchases: number;
  /** Recurrences still expected before it closes. */
  forecast: number;
  /** posted + forecast. */
  expectedTotal: number;
  /** Income the household's monthly income recurrences are expected to bring in that month. */
  expectedIncome: number;
  /** expectedTotal / expectedIncome, rounded to four decimals; null when no income is expected. */
  incomeShare: number | null;
}

export interface CommitmentTotals {
  posted: number;
  postedInstallments: number;
  postedRecurrences: number;
  postedPurchases: number;
  forecast: number;
  expectedTotal: number;
  expectedIncome: number;
  incomeShare: number | null;
}

export interface CardCommitment {
  accountId: string;
  months: CommitmentMonth[];
  totals: CommitmentTotals;
}

export interface CommitmentInput {
  month: string;
  closingDate: string;
  dueDate: string | null;
  state: InvoiceState;
  /** Whole statement of the invoice (posted). */
  postedCents: number;
  /** Part of postedCents from installments. */
  installmentCents: number;
  /** Part of postedCents from recurrences already generated. The purchases are postedCents minus both parts. */
  recurringCents: number;
  forecastCents: number;
}

const share = (totalCents: number, incomeCents: number): number | null =>
  incomeCents > 0 ? Math.round((totalCents / incomeCents) * 10000) / 10000 : null;

/** 'YYYY-MM' + n months. */
export function addMonthKey(month: string, n: number): string {
  const index = Number(month.slice(0, 4)) * 12 + (Number(month.slice(5, 7)) - 1) + n;
  return `${String(Math.floor(index / 12)).padStart(4, '0')}-${String((index % 12) + 1).padStart(2, '0')}`;
}

/** Pure part: one line per invoice and the totals, all summed in whole cents. */
export function buildCommitment(
  accountId: string,
  invoices: CommitmentInput[],
  incomeCentsByMonth: ReadonlyMap<string, number>,
): CardCommitment {
  let postedCents = 0;
  let installmentCents = 0;
  let recurringCents = 0;
  let purchaseCents = 0;
  let forecastCents = 0;
  let incomeCents = 0;
  const months = invoices.map((invoice): CommitmentMonth => {
    const monthIncome = incomeCentsByMonth.get(invoice.month) ?? 0;
    const total = invoice.postedCents + invoice.forecastCents;
    // The three parts sum to the statement: purchases are whatever the installments and recurrences do not explain.
    const purchases = invoice.postedCents - invoice.installmentCents - invoice.recurringCents;
    postedCents += invoice.postedCents;
    installmentCents += invoice.installmentCents;
    recurringCents += invoice.recurringCents;
    purchaseCents += purchases;
    forecastCents += invoice.forecastCents;
    incomeCents += monthIncome;
    return {
      month: invoice.month,
      closingDate: invoice.closingDate,
      dueDate: invoice.dueDate,
      state: invoice.state,
      posted: fromCents(invoice.postedCents),
      postedInstallments: fromCents(invoice.installmentCents),
      postedRecurrences: fromCents(invoice.recurringCents),
      postedPurchases: fromCents(purchases),
      forecast: fromCents(invoice.forecastCents),
      expectedTotal: fromCents(total),
      expectedIncome: fromCents(monthIncome),
      incomeShare: share(total, monthIncome),
    };
  });
  return {
    accountId,
    months,
    totals: {
      posted: fromCents(postedCents),
      postedInstallments: fromCents(installmentCents),
      postedRecurrences: fromCents(recurringCents),
      postedPurchases: fromCents(purchaseCents),
      forecast: fromCents(forecastCents),
      expectedTotal: fromCents(postedCents + forecastCents),
      expectedIncome: fromCents(incomeCents),
      incomeShare: share(postedCents + forecastCents, incomeCents),
    },
  };
}

/**
 * The first month a monthly recurrence brings income: the month of its earliest run on or after its start date, found
 * by walking the monthly runs back from the next one. `nextRunAt` alone is not it: once the run of the month in course
 * happened, the next run is next month, and the month in course would lose income it already received.
 * A run on a day the month does not have falls on its last day.
 */
export function firstIncomeMonth(nextRunAt: Date, startDate: Date | null | undefined): string {
  const next = dayString(nextRunAt);
  let month = next.slice(0, 7);
  if (!startDate) return month;
  const start = dayString(startDate);
  const day = Number(next.slice(8, 10));
  // bounded walk: 50 years of monthly runs
  for (let i = 0; i < 600; i += 1) {
    const previous = addMonthKey(month, -1);
    const year = Number(previous.slice(0, 4));
    const monthNumber = Number(previous.slice(5, 7));
    const lastDay = new Date(Date.UTC(year, monthNumber, 0)).getUTCDate();
    if (formatDay(year, monthNumber, Math.min(day, lastDay)) < start) break;
    month = previous;
  }
  return month;
}

/**
 * Income expected per month, in cents, from the household's active MONTHLY income recurrences (their forecast strategy
 * decides the amount). A recurrence counts from the month of its first run (see firstIncomeMonth) to the month of its
 * end date: the month in course counts the income that already came in, because it is the income of the month that is
 * compared with the invoice, not what is still to arrive. Other frequencies are left out: this is a reference line for
 * the card, not a cash-flow projection.
 * An employment linked to a salary recurrence replaces that recurrence's amount with the calculated net paid in the
 * month, and adds the 13th, vacation and FGTS birthday withdrawal of the month they fall in (nothing is filtered by
 * today: it is the income of the month). Without a linked employment the result is the one of the recurrences alone.
 * Benefits paid per business day: a benefit linked to a recurrence replaces that recurrence's amount with the calculated
 * value of the month it pays; one without a recurrence adds its own value in its payment month. A benefit that is not
 * available money (`isAvailableCash` false) is never income here.
 * With `personId` only the income of that person's employments counts (their salary, extras and benefits): recurrences
 * no employment feeds cannot be attributed to a person and are left out.
 */
export async function expectedIncomeByMonth(householdId: string, months: readonly string[], filter: { personId?: string } = {}): Promise<Map<string, number>> {
  const result = new Map<string, number>(months.map((m) => [m, 0]));
  const payroll = await loadPayrollLinks(householdId, { personId: filter.personId });
  const rows = await prisma.recurringTransaction.findMany({ where: { householdId, isActive: true, frequency: 'MONTHLY' } });
  if (rows.length > 0) {
    const batch = await forecastBatch(prisma, rows);
    for (const row of rows) {
      if (!batch.isIncome(row)) continue;
      const first = firstIncomeMonth(row.nextRunAt, row.startDate);
      const last = row.endDate ? dayString(row.endDate).slice(0, 7) : null;
      const link = payroll.find((l) => l.recurringTransactionId === row.id);
      const benefitOwner = link ? undefined : payroll.find((l) => (l.data.benefits ?? []).some((b) => b.recurringTransactionId === row.id));
      const benefit = benefitOwner?.data.benefits?.find((b) => b.recurringTransactionId === row.id);
      if (filter.personId && !link && !benefit) continue;
      for (const month of months) {
        if (month < first || (last && month > last)) continue;
        const calc = link ? salaryPaidInMonth(link.data, month) : null;
        const benefitCalc = benefit && benefitOwner ? benefitPaidInMonth(benefitOwner.data, benefit, month) : null;
        result.set(month, (result.get(month) ?? 0) + (calc ? calc.netCents : benefitCalc ? benefitCalc.amountCents : toCents(batch.expected(row, month).amount)));
      }
    }
  }
  // 13th, vacations and birthday withdrawals of the employments that feed an active salary recurrence
  if (payroll.length > 0 && months.length > 0) {
    const sorted = [...months].sort();
    const from = `${sorted[0]}-01`;
    const to = formatDay(Number(sorted[sorted.length - 1]!.slice(0, 4)), Number(sorted[sorted.length - 1]!.slice(5, 7)), 31);
    for (const link of payroll) {
      if (!link.recurrenceActive) continue;
      for (const e of extraPayrollEvents(link.data, { from, to })) {
        const month = e.date.slice(0, 7);
        if (result.has(month)) result.set(month, (result.get(month) ?? 0) + e.netCents);
      }
    }
  }
  // Benefits paid per business day without a recurrence, in the month they are paid
  for (const link of payroll) {
    for (const b of link.data.benefits ?? []) {
      if (b.recurringTransactionId || !b.isAvailableCash) continue;
      for (const month of months) {
        const ev = benefitPaidInMonth(link.data, b, month);
        if (ev) result.set(month, (result.get(month) ?? 0) + ev.amountCents);
      }
    }
  }
  return result;
}

/**
 * The card's next invoices side by side: what is already on each one, what the recurrences will still add, and the
 * income expected for the same month. Read-only: it reuses the invoice calculation, month by month.
 */
export async function getCreditCardCommitment(
  accountId: string,
  householdId: string,
  options: { months?: number; from?: string; today?: Date; personId?: string } = {},
): Promise<CardCommitment> {
  if (options.personId) await requirePerson(householdId, options.personId);
  const count = Math.min(12, Math.max(1, options.months ?? 6));
  const today = options.today ?? utcToday();
  const from = options.from ?? dayString(today).slice(0, 7);
  const keys = Array.from({ length: count }, (_, i) => addMonthKey(from, i));

  const invoices: CommitmentInput[] = [];
  for (const month of keys) {
    const { data } = await calculateCreditCardInvoice(accountId, month, householdId, { limit: 1 }, { today });
    invoices.push({
      month,
      closingDate: data.closingDate,
      dueDate: data.dueDate,
      state: data.state,
      postedCents: toCents(data.statementTotal),
      installmentCents: toCents(data.statementInstallments ?? 0),
      recurringCents: toCents(data.statementRecurrences ?? 0),
      forecastCents: toCents(data.forecast.total),
    });
  }
  return buildCommitment(accountId, invoices, await expectedIncomeByMonth(householdId, keys, { personId: options.personId }));
}
